CREATE TABLE prenotazioni (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    occurrence_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    created_by BIGINT,
    created_at TIMESTAMP NOT NULL,
    cancelled_at TIMESTAMP,
    CONSTRAINT fk_prenotazioni_customer
        FOREIGN KEY (customer_id) REFERENCES utenti (id),
    CONSTRAINT fk_prenotazioni_occurrence
        FOREIGN KEY (occurrence_id) REFERENCES agenda_corsi (id),
    CONSTRAINT fk_prenotazioni_created_by
        FOREIGN KEY (created_by) REFERENCES utenti (id),
    CONSTRAINT uk_prenotazioni_customer_occurrence
        UNIQUE (customer_id, occurrence_id)
);

CREATE INDEX idx_prenotazioni_customer_id ON prenotazioni (customer_id);
CREATE INDEX idx_prenotazioni_occurrence_id ON prenotazioni (occurrence_id);
CREATE INDEX idx_prenotazioni_created_by ON prenotazioni (created_by);
CREATE INDEX idx_prenotazioni_occurrence_status ON prenotazioni (occurrence_id, status);