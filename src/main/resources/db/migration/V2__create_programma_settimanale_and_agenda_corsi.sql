CREATE TABLE programma_settimanale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corsi_id BIGINT NOT NULL,
    day_of_week INTEGER NOT NULL,
    start_time TIME NOT NULL,
    default_capacity INTEGER NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE,
    active BOOLEAN NOT NULL,
    CONSTRAINT fk_programma_settimanale_corsi
        FOREIGN KEY (corsi_id) REFERENCES corsi (id)
);

CREATE INDEX idx_programma_settimanale_corsi_id ON programma_settimanale (corsi_id);

CREATE TABLE agenda_corsi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programma_settimanale_id BIGINT NOT NULL,
    lesson_date DATE NOT NULL,
    start_time TIME NOT NULL,
    capacity INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_agenda_corsi_programma
        FOREIGN KEY (programma_settimanale_id) REFERENCES programma_settimanale (id),
    CONSTRAINT uk_agenda_corsi_programma_data
        UNIQUE (programma_settimanale_id, lesson_date)
);

CREATE INDEX idx_agenda_corsi_programma_id ON agenda_corsi (programma_settimanale_id);